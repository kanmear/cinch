// Command catchmatrix writes bench/catch-matrix.md: every defect class cinch's
// checks are tested against, and whether each is caught. The table is built
// from `// catch-matrix: <check> | <verdict> | <defect>` lines in the doc
// comments of tests under internal/cinch, so it can't drift from the suite;
// TestCatchMatrixIsCurrent fails when the committed file is stale.
//
// Usage: go run ./bench/catchmatrix [-root DIR] [-o FILE]
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const annotationPrefix = "catch-matrix:"

// checkOrder is the order checks appear in the matrix, matching the order
// `cinch check` reports them.
var checkOrder = []string{"links", "rules", "index", "generated", "core", "commit", "hooks"}

// verdicts, in table order, with the meaning printed in the legend.
var verdicts = []struct{ name, meaning string }{
	{"caught", "a finding; fails `cinch check` and blocks the hook that runs the check"},
	{"warns", "reported as a skip line; never blocks"},
	{"gap", "a real defect cinch doesn't see; the test asserts it passes, so a change in either direction updates this table"},
	{"not a defect", "looks like a defect, and correctly passes"},
	{"control", "a known-good case that must stay unflagged"},
}

type entry struct {
	check, verdict, defect string
	test, file             string
}

func main() {
	root := flag.String("root", ".", "repository root")
	out := flag.String("o", filepath.Join("bench", "catch-matrix.md"), "output file, relative to -root")
	flag.Parse()

	text, err := generate(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "catchmatrix:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(filepath.Join(*root, *out), []byte(text), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "catchmatrix:", err)
		os.Exit(1)
	}
}

// generate renders the matrix from the annotated tests under root.
func generate(root string) (string, error) {
	entries, err := collect(filepath.Join(root, "internal", "cinch"))
	if err != nil {
		return "", err
	}
	return render(entries), nil
}

func collect(dir string) ([]entry, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*_test.go"))
	if err != nil {
		return nil, err
	}
	sort.Strings(paths)

	var entries []entry
	var problems []string
	fset := token.NewFileSet()
	for _, path := range paths {
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || !strings.HasPrefix(fn.Name.Name, "Test") {
				continue
			}
			line, found := annotation(fn.Doc)
			if !found {
				if strings.HasPrefix(fn.Name.Name, "TestSeededDefect") {
					problems = append(problems, fmt.Sprintf("%s: %s has no %q line", filepath.Base(path), fn.Name.Name, annotationPrefix))
				}
				continue
			}
			e, err := parseAnnotation(line)
			if err != nil {
				problems = append(problems, fmt.Sprintf("%s: %s: %v", filepath.Base(path), fn.Name.Name, err))
				continue
			}
			e.test, e.file = fn.Name.Name, filepath.Base(path)
			entries = append(entries, e)
		}
	}
	if len(problems) > 0 {
		return nil, fmt.Errorf("%d problem(s):\n  %s", len(problems), strings.Join(problems, "\n  "))
	}
	return entries, nil
}

func annotation(doc *ast.CommentGroup) (string, bool) {
	if doc == nil {
		return "", false
	}
	for _, c := range doc.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if rest, ok := strings.CutPrefix(text, annotationPrefix); ok {
			return strings.TrimSpace(rest), true
		}
	}
	return "", false
}

func parseAnnotation(line string) (entry, error) {
	fields := strings.Split(line, "|")
	if len(fields) != 3 {
		return entry{}, fmt.Errorf("want <check> | <verdict> | <defect>, got %q", line)
	}
	for i := range fields {
		fields[i] = strings.TrimSpace(fields[i])
	}
	e := entry{check: fields[0], verdict: fields[1], defect: fields[2]}
	if indexOf(checkOrder, e.check) < 0 {
		return entry{}, fmt.Errorf("unknown check %q", e.check)
	}
	if verdictRank(e.verdict) < 0 {
		return entry{}, fmt.Errorf("unknown verdict %q", e.verdict)
	}
	if e.defect == "" {
		return entry{}, fmt.Errorf("empty defect in %q", line)
	}
	return e, nil
}

func render(entries []entry) string {
	sort.SliceStable(entries, func(i, j int) bool {
		a, b := entries[i], entries[j]
		if a.check != b.check {
			return indexOf(checkOrder, a.check) < indexOf(checkOrder, b.check)
		}
		return verdictRank(a.verdict) < verdictRank(b.verdict)
	})

	counts := map[string]int{}
	for _, e := range entries {
		counts[e.verdict]++
	}

	var b strings.Builder
	b.WriteString("<!-- generated by bench/catchmatrix from the catch-matrix lines in internal/cinch/*_test.go; regenerate with `make catch-matrix` -->\n\n")
	b.WriteString("# Catch matrix\n\n")
	b.WriteString("Every defect class cinch's checks are tested against, and what each check does with it. ")
	b.WriteString("Each row is one test in `internal/cinch`, which passes in `go test ./...`; ")
	b.WriteString("the row is generated from that test, so the table and the suite can't disagree.\n\n")

	var summary []string
	for _, v := range verdicts {
		if counts[v.name] > 0 {
			summary = append(summary, fmt.Sprintf("%d %s", counts[v.name], v.name))
		}
	}
	fmt.Fprintf(&b, "**%d defect classes:** %s.\n\n", len(entries), strings.Join(summary, ", "))

	b.WriteString("| Verdict | Meaning |\n|---|---|\n")
	for _, v := range verdicts {
		fmt.Fprintf(&b, "| %s | %s |\n", v.name, v.meaning)
	}

	current := ""
	for _, e := range entries {
		if e.check != current {
			current = e.check
			fmt.Fprintf(&b, "\n## `%s`\n\n| Defect | Verdict | Test |\n|---|---|---|\n", current)
		}
		fmt.Fprintf(&b, "| %s | %s | `%s` (`%s`) |\n", e.defect, e.verdict, e.test, e.file)
	}

	b.WriteString(outOfReach)
	return b.String()
}

// outOfReach lists defects no unit test here can express, so a reader
// doesn't mistake their absence from the tables for coverage.
const outOfReach = `
## Out of reach of these tests

- **` + "`git commit --no-verify`" + `.** Git skips pre-commit and commit-msg, so no hook check runs. CI
  running ` + "`cinch check`" + ` catches what lands; the field log (plan 19) counts it, because
  post-commit still fires.
- **A rule reworded to mean something else while its marked test stays the same.** Each run sees
  one snapshot, in which the rule and its marker still resolve. Only a review of the diff
  catches it.
- **Docs that describe code which has since changed, where no rule is involved.** That is the
  staleness heuristic plan 09 gates; nothing ships for it yet.
`

func indexOf(list []string, s string) int {
	for i, v := range list {
		if v == s {
			return i
		}
	}
	return -1
}

func verdictRank(name string) int {
	for i, v := range verdicts {
		if v.name == name {
			return i
		}
	}
	return -1
}
