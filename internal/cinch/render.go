//go:embed docs/philosophy.md
var philosophySrc string

//go:embed docs/templates
var templatesFS embed.FS

const templatesDir = "docs/templates"

// varRe matches {{key}} tokens. Literal substitution only — no loops, no
// conditionals, no template engine.
var varRe = regexp.MustCompile(`\{\{([a-zA-Z0-9_.-]+)\}\}`)

// substitute replaces every {{key}} in body with vars[key]. An undefined
// variable is an error, never an empty string — it returns every key it
// could not resolve so the caller can report them all at once.
func substitute(body string, vars map[string]string) (string, []string) {
	missing := map[string]bool{}
	out := varRe.ReplaceAllStringFunc(body, func(m string) string {
		key := m[2 : len(m)-2]
		if v, ok := vars[key]; ok {
			return v
		}
		missing[key] = true
		return m
	})
	return out, sortedKeys(missing)
}

func bodyHash(body string) string {
	sum := sha256.Sum256([]byte(body))
	return hex.EncodeToString(sum[:])[:16]
}

// headerPrefix is the comment-syntax-agnostic marker every generated file
// carries near its top, used by checkGenerated to tell a generated file
// apart from a hand-authored one regardless of comment style.
const headerPrefix = "generated by cinch"

// fileStyle selects a renderFile's comment syntax for header().
type fileStyle int

const (
	styleMarkdown fileStyle = iota
	styleShell
)

// header builds the generated-file header for body, stamped with source (the
// embedded template's path, e.g. "docs/philosophy.md", or "generated" for a
// derived file like the doc map or a hook shim) so a re-render is
// idempotent: identical source + identical manifest always produces
// identical bytes, and a re-render diff proves tampering.
//
// Style-aware: markdown keeps the `<!-- ... -->` form; a shell script needs
// its shebang as the literal first line, so the marker becomes a
// `#`-comment on the line below it instead.
func header(source, body string, style fileStyle) string {
	marker := fmt.Sprintf("%s from %s — do not edit; body-sha: %s", headerPrefix, source, bodyHash(body))
	if style == styleShell {
		return "#!/bin/sh\n# " + marker + "\n\n"
	}
	return "<!-- " + marker + " -->\n\n"
}

// hasGeneratedHeader reports whether data carries a header() marker in its
// first two lines — line 1 for markdown, line 2 for shell (after the
// shebang). Used by checkGenerated to spot orphaned generated files
// regardless of style.
func hasGeneratedHeader(data string) bool {
	lines := strings.SplitN(data, "\n", 3)
	for i := 0; i < len(lines) && i < 2; i++ {
		if strings.Contains(lines[i], headerPrefix) {
			return true
		}
	}
	return false
}

// renderFile is one output cinch render produces.
type renderFile struct {
	Dest   string // repo-relative path to write
	Source string // embedded source path, for the header
	Body   string // rendered body (post-substitution), pre-header
	Mode   os.FileMode // 0 defaults to 0o644 at write time; hook shims use 0o755
	Style  fileStyle
}

// renderAll produces every Stage 2+ output in memory: philosophy copied
// verbatim (it has no variables — see docs/philosophy.md), every
// docs/templates/*.md file substituted against the manifest, and hook shims.
// Workflow and doc navigation are computed on demand (`cinch workflows`,
// `cinch docs`) rather than persisted here — see workflow.go and docs.go.
func renderAll(m *Manifest) ([]renderFile, error) {
	entries, err := fs.ReadDir(templatesFS, templatesDir)
	if err != nil {
		return nil, fmt.Errorf("internal: reading embedded templates: %w", err)
	}

	docsRoot := docsPathValue(m)
	workflowsDir := docsRoot + "/" + workflowsSubdir
	hooksDir := hooksPathValue(m)

	vars := map[string]string{}
	if m != nil {
		for k, v := range m.Vars {
			vars[k] = v
		}
	}
	vars[pathsDocsKey] = docsRoot

	var files []renderFile
	var errLines []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		src := templatesDir + "/" + name
		raw, err := fs.ReadFile(templatesFS, src)
		if err != nil {
			return nil, fmt.Errorf("internal: reading embedded %s: %w", src, err)
		}
		body, missing := substitute(string(raw), vars)
		if len(missing) > 0 {
			errLines = append(errLines, fmt.Sprintf("%s: undefined manifest variables: %s", src, strings.Join(missing, ", ")))
			continue
		}
		files = append(files, renderFile{Dest: workflowsDir + "/" + name, Source: src, Body: body})
	}
	if len(errLines) > 0 {
		return nil, fmt.Errorf("%s", strings.Join(errLines, "\n"))
	}

	files = append(files, renderFile{Dest: workflowsDir + "/doc-philosophy.md", Source: "docs/philosophy.md", Body: philosophySrc})

	sort.Slice(files, func(i, j int) bool { return files[i].Dest < files[j].Dest })

	files = append(files, buildHookShims(hooksDir)...)

	return files, nil
}

const defaultHooksPath = ".githooks"

// hookEvents are the git hooks CmdHook dispatches — the only shims render
// generates.
var hookEvents = []string{"pre-commit", "commit-msg"}

// hooksPathValue returns m's paths.hooks value, or the default when unset
// or m is nil.
func hooksPathValue(m *Manifest) string {
	if m != nil {
		if v, ok := m.Vars["paths.hooks"]; ok && v != "" {
			return v
		}
	}
	return defaultHooksPath
}

// buildHookShims renders one thin shim per supported git hook event under
// hooksDir. The body never changes when the manifest changes — the actual
// dispatch table (hooks.<event>.* entries) is read at runtime by `cinch
// hook`, not baked into the shim — so editing the manifest takes effect
// immediately with no re-render, and the shims stay byte-stable across
// manifest edits.
func buildHookShims(hooksDir string) []renderFile {
	var files []renderFile
	for _, event := range hookEvents {
		files = append(files, renderFile{
			Dest:   hooksDir + "/" + event,
			Source: "generated",
			Body:   "exec cinch hook " + event + " \"$@\"\n",
			Mode:   0o755,
			Style:  styleShell,
		})
	}
	return files
}

// CmdRender implements `cinch render`: writes every Stage 2 output under
// root, header-stamped. Idempotent — re-running with the same manifest and
// embedded templates produces byte-identical files, so a re-render diff
// proves tampering.
func CmdRender(root string) int {
	m, err := loadManifest(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "cinch: "+err.Error())
		return 1
	}

	files, err := renderAll(m)
	if err != nil {
		fmt.Fprintln(os.Stderr, "cinch: "+err.Error())
		return 1
	}

	for _, f := range files {
		dst := filepath.Join(root, f.Dest)
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "cinch: "+err.Error())
			return 1
		}
		content := header(f.Source, f.Body, f.Style) + f.Body
		mode := f.Mode
		if mode == 0 {
			mode = 0o644
		}
		if err := os.WriteFile(dst, []byte(content), mode); err != nil {
			fmt.Fprintln(os.Stderr, "cinch: "+err.Error())
			return 1
		}
		fmt.Printf("rendered %s\n", f.Dest)
	}
	return 0
}
